const imageSource = (value: unknown): string => {
    const source = typeof value === 'string' ? value.trim() : '';
    return ['', 'EMPTY', 'EMPTY_BSHOT', 'undefined', 'null'].includes(source) ? '' : source;
};

/** Storage location does not determine quality: a Nano preview can have an S3 URL. */
export const isPreviewSceneImage = (value: unknown, ...previewSources: unknown[]): boolean => {
    const source = imageSource(value);
    return Boolean(source) && previewSources.some(preview => imageSource(preview) === source);
};

export type SceneImageQuality = 'preview' | 'final';

/** Quality follows the generated bytes through URL replacement, never the URL scheme. */
export class SceneImageProvenance {
    private sources = new Map<string, SceneImageQuality>();

    mark(quality: SceneImageQuality, ...values: unknown[]): void {
        for (const value of values) {
            const source = imageSource(value);
            if (source) this.sources.set(source, quality);
        }
    }

    quality(...values: unknown[]): SceneImageQuality | undefined {
        for (const value of values) {
            const quality = this.sources.get(imageSource(value));
            if (quality) return quality;
        }
        return undefined;
    }

    stored(receipt: { previewUrl?: string; sdUrl: string; hdUrl: string; quality?: SceneImageQuality }): void {
        this.mark(receipt.quality || this.quality(receipt.previewUrl, receipt.sdUrl, receipt.hdUrl) || 'final', receipt.sdUrl, receipt.hdUrl);
    }
}

export const hasFinalSceneImage = ({
    hdImageUrl,
    displayImageUrl,
    nanoImageUrl,
    quality,
    hasLocalImage,
}: {
    hdImageUrl: unknown;
    displayImageUrl?: unknown;
    nanoImageUrl?: unknown;
    quality?: SceneImageQuality;
    hasLocalImage?: boolean;
}): boolean => {
    const hd = imageSource(hdImageUrl);
    const display = imageSource(displayImageUrl);
    if (!hd && !display && !hasLocalImage) return false;
    if (quality) return quality === 'final';
    // Direct Nano sources are known previews even before their first storage
    // receipt. Dummy-card presentation alone is not proof of image quality.
    return !isPreviewSceneImage(hd, nanoImageUrl)
        && !isPreviewSceneImage(display || hd, nanoImageUrl);
};
